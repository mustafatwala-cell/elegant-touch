CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    cat TEXT NOT NULL CHECK (cat IN ('jewellery', 'bags', 'accessories', 'gifts')),
    img TEXT NOT NULL,
    images TEXT[] NOT NULL DEFAULT '{}',
    "desc" TEXT NOT NULL DEFAULT '',
    sizes TEXT[] DEFAULT NULL,
    material TEXT NOT NULL DEFAULT 'ستانلس ستيل مطلي ذهب',
    stock TEXT NOT NULL DEFAULT 'متوفر',
    features TEXT[] NOT NULL DEFAULT '{}',
    featured BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_products_cat ON public.products (cat);
CREATE INDEX IF NOT EXISTS idx_products_featured ON public.products (featured);

-- Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- RLS Policy: Public SELECT only (anonymous & authenticated customers can view products)
DROP POLICY IF EXISTS "Allow public read access to products" ON public.products;
CREATE POLICY "Allow public read access to products"
    ON public.products
    FOR SELECT
    TO public
    USING (true);

-- Note: No INSERT, UPDATE, or DELETE policies are granted to the public role.
-- Modifications are strictly restricted to authenticated store administrators / service_role.
